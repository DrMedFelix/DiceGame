    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        String name = jTextField1.getText().trim();

        if (name.isEmpty()) {
            zeigeFehler("Bitte gib einen Namen ein!");
            return;
        }

        if (verwaltung.userExistiert(name)) {
            zeigeHinweis("Ein Spieler mit diesem Namen existiert bereits!");
            return;
        }

        User neu = verwaltung.neuerUser(name, 0);
        if (neu != null) {
            zeigeErfolg("Spieler '" + neu.getName() + "' erfolgreich angelegt!");
            jTextField1.setText("");
            ladeUserInComboBox();
            jComboBox1.setSelectedItem(neu.getName());
        } else if (name.length() > UserVerwaltung.MAX_NAME_LAENGE) {
            zeigeFehler("Der Name ist zu lang (max. " + UserVerwaltung.MAX_NAME_LAENGE + " Zeichen)!");
        } else {
            zeigeFehler("Fehler beim Speichern des Spielers!");
        }
    }

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        String ausgewaehlterName = (String) jComboBox1.getSelectedItem();

        if (ausgewaehlterName == null || ausgewaehlterName.equals(KEINE_SPIELER)) {
            zeigeHinweis("Bitte wähle einen gültigen Spieler aus oder erstelle einen neuen!");
            return;
        }

        User spieler = verwaltung.sucheUser(ausgewaehlterName);
        if (spieler == null) {
            zeigeFehler("Der Spieler konnte nicht geladen werden!");
            return;
        }

        if (hauptFenster != null) {
            hauptFenster.zeigeNaechstesFenster(this, new HauptMenueFelix(hauptFenster, spieler));
        }
    }


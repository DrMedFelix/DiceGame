package dicegame;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class Datenbankschnittstelle {

    private static final String DB_URL = "jdbc:hsqldb:file:data/DiceGameDB";
    private Connection conn;

    // Verbindet sich und legt die Tabelle an, falls sie noch nicht existiert.
    public Datenbankschnittstelle() throws SQLException {
        conn = DriverManager.getConnection(DB_URL, "SA", "");
        try (Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS Spieler ("
                    + "id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY, "
                    + "name VARCHAR(50) NOT NULL UNIQUE, "
                    + "waehrung INTEGER DEFAULT 0 NOT NULL)");
        }
    }

    public void beenden() throws SQLException {
        if (conn != null && !conn.isClosed()) {
            try (Statement stmt = conn.createStatement()) {
                stmt.executeUpdate("SHUTDOWN");
            }
            conn.close();
        }
    }

    public boolean istLeer() throws SQLException {
        try (Statement stmt = conn.createStatement();
             ResultSet rst = stmt.executeQuery("SELECT COUNT(*) FROM Spieler")) {
            rst.next(); //rückt auf die ersten Zeile
            return rst.getInt(1) == 0; // wenn 0, dann nix drin (true)
        }
    }

    public boolean existiert(String name) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT COUNT(*) FROM Spieler WHERE name = ?")) {
            ps.setString(1, name); //erste fragezeichen wird mit name eingesetzt
            try (ResultSet rst = ps.executeQuery()) {
                rst.next();
                return rst.getInt(1) > 0; //wenn 0, dann existiert name nicht (false)
            }
        }
    }

    public boolean speichereBenutzername(String name) throws SQLException {
        if (name == null || name.trim().isEmpty() || existiert(name)) {
            return false;
        }
        try (PreparedStatement ps = conn.prepareStatement(
                "INSERT INTO Spieler (name) VALUES (?)")) {
            ps.setString(1, name);
            ps.executeUpdate();
        }
        return true;
    }

    public List<String> ladeAlleBenutzernamen() throws SQLException {
        List<String> namen = new ArrayList<>();
        try (Statement stmt = conn.createStatement();
             ResultSet rst = stmt.executeQuery("SELECT name FROM Spieler ORDER BY id")) {
            while (rst.next()) {
                namen.add(rst.getString("name"));
            }
        }
        return namen;
    }

    public boolean loescheBenutzername(String name) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement(
                "DELETE FROM Spieler WHERE name = ?")) {
            ps.setString(1, name);
            return ps.executeUpdate() > 0;
        }
    }
}
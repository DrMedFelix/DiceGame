package dicegame;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;

public class Datenbankschnittstelle {

    private static final String TREIBERNAME = "org.hsqldb.jdbc.JDBCDriver";
    private static final String DB_URL = "jdbc:hsqldb:file:data/DiceGameDB";

    private static final String[] NEUE_SPALTEN = {
        "spielzeit", "gewonnene_runden", "verlorene_runden", "winstreak"
    };

    private static Datenbankschnittstelle instance;
    private Connection conn;

    public static Datenbankschnittstelle getInstance() {
        if (instance == null) {
            instance = new Datenbankschnittstelle();
        }
        return instance;
    }

    private Datenbankschnittstelle() {
        try {
            Class.forName(TREIBERNAME);
        } catch (ClassNotFoundException exc) {
            throw new IllegalStateException("HSQLDB-Treiber nicht gefunden (hsqldb.jar im Projekt?)", exc);
        }
    }

    private void connect() throws SQLException {
        conn = DriverManager.getConnection(DB_URL, "SA", "");
        try (Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("CREATE TABLE IF NOT EXISTS Spieler ("
                    + "id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY, "
                    + "name VARCHAR(50) NOT NULL UNIQUE, "
                    + "waehrung INTEGER DEFAULT 0 NOT NULL, "
                    + "spielzeit INTEGER DEFAULT 0 NOT NULL, "
                    + "gewonnene_runden INTEGER DEFAULT 0 NOT NULL, "
                    + "verlorene_runden INTEGER DEFAULT 0 NOT NULL, "
                    + "winstreak INTEGER DEFAULT 0 NOT NULL)");
            for (String spalte : NEUE_SPALTEN) {
                stmt.executeUpdate("ALTER TABLE Spieler ADD COLUMN IF NOT EXISTS "
                        + spalte + " INTEGER DEFAULT 0 NOT NULL");
            }
        } catch (SQLException exc) {
            try {
                close(); 
            } catch (SQLException ignoriert) {
            }
            throw exc;
        }
    }

    private void close() throws SQLException {
        if (conn != null && !conn.isClosed()) {
            try (Statement stmt = conn.createStatement()) {
                stmt.executeUpdate("SHUTDOWN");
            }
            conn.close();
        }
    }

    private User userAusZeile(ResultSet rst) throws SQLException {
        return new User(
                rst.getInt("id"),
                rst.getString("name"),
                rst.getInt("waehrung"),
                rst.getInt("spielzeit"),
                rst.getInt("gewonnene_runden"),
                rst.getInt("verlorene_runden"),
                rst.getInt("winstreak"));
    }

    public List<User> alleUser() throws SQLException {
        List<User> alle = new ArrayList<>();
        connect();
        try (Statement stmt = conn.createStatement();
             ResultSet rst = stmt.executeQuery("SELECT * FROM Spieler ORDER BY id")) {
            while (rst.next()) {
                alle.add(userAusZeile(rst));
            }
        } finally {
            close();
        }
        return alle;
    }

    public User sucheUserNachName(String name) throws SQLException {
        User user = null;
        connect();
        try (PreparedStatement ps = conn.prepareStatement(
                "SELECT * FROM Spieler WHERE name = ?")) {
            ps.setString(1, name);
            try (ResultSet rst = ps.executeQuery()) {
                if (rst.next()) {
                    user = userAusZeile(rst);
                }
            }
        } finally {
            close();
        }
        return user;
    }

    public boolean neuerUser(User user) throws SQLException {
        boolean result = false;
        connect();
        try (PreparedStatement ps = conn.prepareStatement(
                "INSERT INTO Spieler (name, waehrung, spielzeit, gewonnene_runden, "
                + "verlorene_runden, winstreak) VALUES (?, ?, ?, ?, ?, ?)",
                Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, user.getName());
            ps.setInt(2, user.getWaehrung());
            ps.setInt(3, user.getSpielzeit());
            ps.setInt(4, user.getGewonneneRunden());
            ps.setInt(5, user.getVerloreneRunden());
            ps.setInt(6, user.getWinstreak());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    user.setId(keys.getInt(1));
                    result = true;
                }
            }
        } finally {
            close();
        }
        return result;
    }

    public boolean speichereUser(User user) throws SQLException {
        boolean result;
        connect();
        try (PreparedStatement ps = conn.prepareStatement(
                "UPDATE Spieler SET name = ?, waehrung = ?, spielzeit = ?, "
                + "gewonnene_runden = ?, verlorene_runden = ?, winstreak = ? WHERE id = ?")) {
            ps.setString(1, user.getName());
            ps.setInt(2, user.getWaehrung());
            ps.setInt(3, user.getSpielzeit());
            ps.setInt(4, user.getGewonneneRunden());
            ps.setInt(5, user.getVerloreneRunden());
            ps.setInt(6, user.getWinstreak());
            ps.setInt(7, user.getId());
            result = ps.executeUpdate() != 0;
        } finally {
            close();
        }
        return result;
    }

    public boolean loescheUser(User user) throws SQLException {
        boolean result;
        connect();
        try (PreparedStatement ps = conn.prepareStatement(
                "DELETE FROM Spieler WHERE id = ?")) {
            ps.setInt(1, user.getId());
            result = ps.executeUpdate() != 0;
        } finally {
            close();
        }
        return result;
    }
}